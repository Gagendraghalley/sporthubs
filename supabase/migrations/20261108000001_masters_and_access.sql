-- New rows ([..._id] null) or changes. Rows are turned off, not deleted:
-- addresses keep pointing at them.

create or replace function public.master_save_dzongkhag(dzongkhag_id int, name text, active boolean default true)
returns int
language plpgsql
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  p_id int := master_save_dzongkhag.dzongkhag_id;
  p_name text := regexp_replace(trim(coalesce(master_save_dzongkhag.name, '')), '\s+', ' ', 'g');
  p_active boolean := coalesce(master_save_dzongkhag.active, true);
  v_id int;
begin
  if not public.has_permission('masters.manage') then
    raise exception 'Only people who keep the master data can change it.';
  end if;
  if char_length(p_name) not between 2 and 60 then
    raise exception 'Enter the dzongkhag''s name (2 to 60 letters).';
  end if;
  if p_id is null then
    insert into public.dzongkhags (name, is_active) values (p_name, p_active) returning dzongkhags.id into v_id;
  else
    update public.dzongkhags d set name = p_name, is_active = p_active where d.id = p_id returning d.id into v_id;
    if v_id is null then
      raise exception 'This dzongkhag no longer exists.';
    end if;
  end if;
  return v_id;
exception when unique_violation then
  raise exception '% is already on the list.', p_name;
end;
$$;

create or replace function public.master_save_gewog(gewog_id int, dzongkhag_id int, name text, kind text default 'gewog',
                                                    active boolean default true)
returns int
language plpgsql
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  p_id int := master_save_gewog.gewog_id;
  p_dzongkhag int := master_save_gewog.dzongkhag_id;
  p_name text := regexp_replace(trim(coalesce(master_save_gewog.name, '')), '\s+', ' ', 'g');
  p_kind text := coalesce(master_save_gewog.kind, 'gewog');
  p_active boolean := coalesce(master_save_gewog.active, true);
  v_id int;
begin
  if not public.has_permission('masters.manage') then
    raise exception 'Only people who keep the master data can change it.';
  end if;
  if not exists (select 1 from public.dzongkhags d where d.id = p_dzongkhag) then
    raise exception 'Choose the dzongkhag.';
  end if;
  if p_kind not in ('gewog', 'thromde') then
    raise exception 'Choose gewog or thromde.';
  end if;
  if char_length(p_name) not between 2 and 80 then
    raise exception 'Enter the name (2 to 80 letters).';
  end if;
  if p_id is null then
    insert into public.gewogs (dzongkhag_id, name, kind, is_active) values (p_dzongkhag, p_name, p_kind, p_active)
    returning gewogs.id into v_id;
  else
    update public.gewogs g set dzongkhag_id = p_dzongkhag, name = p_name, kind = p_kind, is_active = p_active
    where g.id = p_id returning g.id into v_id;
    if v_id is null then
      raise exception 'This gewog no longer exists.';
    end if;
  end if;
  return v_id;
exception when unique_violation then
  raise exception '% is already in that dzongkhag.', p_name;
end;
$$;

