-- Super admins: the SportsHub team's top level. Deactivated ones aren't.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin' and p.is_active
  );
$$;

-- The caller has platform permission [perm] (super admins have them all).
create or replace function public.has_permission(perm text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_admin() or exists (
    select 1
    from public.user_roles ur
    join public.roles r on r.id = ur.role_id and r.is_active and r.scope = 'platform'
    join public.role_permissions rp on rp.role_id = r.id and rp.permission_key = perm
    join public.profiles p on p.id = ur.user_id and p.is_active
    where ur.user_id = (select auth.uid())
  );
$$;

-- The caller's role at [venue]: a role key, or null. A role that is turned
-- off, or a person who is, counts as none.
create or replace function public.venue_role(venue uuid)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select s.role
  from public.venue_staff s
  join public.roles r on r.key = s.role and r.is_active
  join public.profiles p on p.id = s.user_id and p.is_active
  where s.venue_id = venue and s.user_id = (select auth.uid());
$$;

-- The caller may do [perm] at [venue]: their role there has it (the Owner
-- has everything), or they are a super admin.
create or replace function public.has_venue_permission(venue uuid, perm text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_admin() or exists (
    select 1
    from public.venue_staff s
    join public.roles r on r.key = s.role and r.is_active
    join public.profiles p on p.id = s.user_id and p.is_active
    where s.venue_id = venue and s.user_id = (select auth.uid())
      and (r.key = 'owner' or exists (
        select 1 from public.role_permissions rp where rp.role_id = r.id and rp.permission_key = perm
      ))
  );
$$;

-- What the signed-in user may do across SportsHub, for the app's menus.
create or replace function public.my_access()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'is_super_admin', public.is_admin(),
    'is_active', coalesce((select p.is_active from public.profiles p where p.id = (select auth.uid())), false),
    'permissions', coalesce((
      select jsonb_agg(pm.key order by pm.sort_order)
      from public.permissions pm
      where pm.scope = 'platform' and public.has_permission(pm.key)
    ), '[]'::jsonb)
  );
$$;

-- The caller could give [role] (at [venue], for a venue role): super
-- admins any; others only roles whose every permission they have.
create or replace function public.can_give_role(role_id uuid, venue uuid default null)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_role public.roles;
begin
  if public.is_admin() then
    return true;
  end if;
  select * into v_role from public.roles r where r.id = can_give_role.role_id;
  if not found then
    return false;
  end if;
  if v_role.key = 'owner' then
    return false; -- only super admins and user managers hand over a venue
  end if;
  return not exists (
    select 1 from public.role_permissions rp
    where rp.role_id = v_role.id
      and not case when v_role.scope = 'platform' then public.has_permission(rp.permission_key)
                   else public.has_venue_permission(venue, rp.permission_key) end
  );
end;
$$;


