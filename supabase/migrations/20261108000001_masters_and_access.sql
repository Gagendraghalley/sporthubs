-- =====================================================================
-- Master data and access control.
--
-- 1. Location masters: dzongkhags -> gewogs (and thromdes) -> villages, for
--    addresses (a gym member's registration). Everyone reads the active
--    ones; people with 'masters.manage' keep them up to date. The rows
--    themselves are in 20261108000002_master_locations_data.sql.
--
-- 2. Roles and permissions:
--    * permissions: what the app can check. The keys are fixed here and in
--      the modules' migrations, because the database functions test them.
--      Two scopes: 'platform' (the SportsHub team: users, roles, masters,
--      venues, modules) and 'venue' (running one gym).
--    * roles: named sets of permissions, made and changed by people with
--      'roles.manage' (Admin -> Roles and permissions). System roles
--      (seeded below) can't be deleted; Owner always has everything.
--    * user_roles: platform roles given to a person.
--    * venue_staff.role: a venue role's key, per venue (owner, manager,
--      staff = 'Front desk', trainer, or any role admins add).
--    * Super admins (profiles.role = 'admin', set in the SQL editor or by
--      another super admin) can do everything, as before.
--    * profiles.is_active: a deactivated person keeps their account but
--      loses every role (and the admin-users Edge Function blocks sign-in).
--    * Nobody can give a permission they don't have themselves (unless they
--      are a super admin), so roles can't be used to climb.
--
-- 3. The core's functions and rules check permissions instead of fixed
--    roles: 'venue.edit', 'venue.staff', 'venue.income', 'venues.verify',
--    'modules.manage'. The defaults keep today's behaviour: Owner and
--    Manager edit the venue and see income, only the Owner adds staff.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. Location masters
-- ---------------------------------------------------------------------

create table if not exists public.dzongkhags (
  id         smallint generated by default as identity primary key,
  name       text not null check (char_length(trim(name)) between 2 and 60),
  is_active  boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists dzongkhags_name_key on public.dzongkhags (lower(name));

-- Gewogs, and the thromdes and towns that stand in for them in cities
-- ('Thim Throm'): both are the level between dzongkhag and village.
create table if not exists public.gewogs (
  id           int generated by default as identity primary key,
  dzongkhag_id smallint not null references public.dzongkhags (id) on delete restrict,
  name         text not null check (char_length(trim(name)) between 2 and 80),
  kind         text not null default 'gewog' check (kind in ('gewog', 'thromde')),
  is_active    boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create unique index if not exists gewogs_name_key on public.gewogs (dzongkhag_id, lower(name));

create table if not exists public.villages (
  id         int generated by default as identity primary key,
  gewog_id   int not null references public.gewogs (id) on delete restrict,
  name       text not null check (char_length(trim(name)) between 1 and 100),
  code       text unique check (code ~ '^[0-9]{7}$'), -- the national code, DDGGVVV, where known
  is_active  boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists villages_name_key on public.villages (gewog_id, lower(name));

drop trigger if exists dzongkhags_updated_at on public.dzongkhags;
create trigger dzongkhags_updated_at before update on public.dzongkhags
  for each row execute function public.set_updated_at();
drop trigger if exists gewogs_updated_at on public.gewogs;
create trigger gewogs_updated_at before update on public.gewogs
  for each row execute function public.set_updated_at();
drop trigger if exists villages_updated_at on public.villages;
create trigger villages_updated_at before update on public.villages
  for each row execute function public.set_updated_at();


-- ---------------------------------------------------------------------
-- 2. Roles and permissions
-- ---------------------------------------------------------------------

create table if not exists public.permissions (
  key         text primary key check (key ~ '^[a-z][a-z_]*(\.[a-z_]+)+$'),
  scope       text not null check (scope in ('platform', 'venue')),
  module_key  text references public.app_modules (key) on delete cascade, -- null: the core
  name        text not null,
  description text,
  sort_order  int not null default 100
);

create table if not exists public.roles (
  id          uuid primary key default gen_random_uuid(),
  -- What venue_staff.role holds. Made from the name; never changes.
  key         text not null unique check (key ~ '^[a-z][a-z0-9_]{1,40}$'),
  scope       text not null check (scope in ('platform', 'venue')),
  name        text not null check (char_length(trim(name)) between 2 and 60),
  description text check (char_length(description) <= 300),
  is_system   boolean not null default false, -- seeded: can't be deleted
  is_active   boolean not null default true,  -- off: nobody gets its permissions
  sort_order  int not null default 100,
  created_by  uuid references public.profiles (id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create unique index if not exists roles_name_key on public.roles (scope, lower(name));

create table if not exists public.role_permissions (
  role_id        uuid not null references public.roles (id) on delete cascade,
  permission_key text not null references public.permissions (key) on delete cascade,
  primary key (role_id, permission_key)
);

-- Platform roles given to a person. (Venue roles are in venue_staff.)
create table if not exists public.user_roles (
  user_id     uuid not null constraint user_roles_user_id_fkey references public.profiles (id) on delete cascade,
  role_id     uuid not null references public.roles (id) on delete restrict,
  assigned_by uuid constraint user_roles_assigned_by_fkey references public.profiles (id) on delete set null,
  created_at  timestamptz not null default now(),
  primary key (user_id, role_id)
);

alter table public.profiles add column if not exists is_active boolean not null default true;

drop trigger if exists roles_updated_at on public.roles;
create trigger roles_updated_at before update on public.roles
  for each row execute function public.set_updated_at();

-- What there is to give, and the roles everyone starts with. A permission
-- or role seen for the first time gets its default pairs; ones already here
-- keep whatever admins have chosen since.
do $$
declare
  v_new_permissions text[];
  v_new_roles text[];
begin
  with saved as (
    insert into public.permissions (key, scope, name, description, sort_order) values
      ('users.manage',   'platform', 'Users',            'Make accounts, give roles, turn people off', 10),
      ('roles.manage',   'platform', 'Roles',            'Make roles and choose their permissions', 20),
      ('masters.manage', 'platform', 'Master data',      'Dzongkhags, gewogs and villages', 30),
      ('venues.verify',  'platform', 'Verify venues',    'See every venue and verify or send back new ones', 40),
      ('modules.manage', 'platform', 'Modules',          'Turn gym membership and other modules on and off', 50),
      ('venue.edit',     'venue',    'Venue details',    'Change details, photos and how to pay', 10),
      ('venue.staff',    'venue',    'Staff',            'Add staff, make their accounts and choose their roles', 20),
      ('venue.income',   'venue',    'Income',           'See payments and income', 30)
    on conflict (key) do update
      set scope = excluded.scope, name = excluded.name, description = excluded.description,
          sort_order = excluded.sort_order
    returning key, (xmax = 0) as inserted
  )
  select coalesce(array_agg(key) filter (where inserted), '{}') into v_new_permissions from saved;

  with saved as (
    insert into public.roles (key, scope, name, description, is_system, sort_order) values
      ('platform_admin', 'platform', 'Administrator', 'Runs SportsHub day to day: users, roles, masters, venues and modules', true, 10),
      ('owner',   'venue', 'Owner',      'Owns the venue: can do everything there', true, 10),
      ('manager', 'venue', 'Manager',    'Runs the venue: details, plans, prices and income', true, 20),
      ('staff',   'venue', 'Front desk', 'Registers members, takes payments and checks people in', true, 30),
      ('trainer', 'venue', 'Trainer',    'Sees members and checks them in', true, 40)
    on conflict (key) do nothing
    returning key
  )
  select coalesce(array_agg(key), '{}') into v_new_roles from saved;

  insert into public.role_permissions (role_id, permission_key)
  select r.id, d.permission_key
  from (values
    ('platform_admin', 'users.manage'), ('platform_admin', 'roles.manage'), ('platform_admin', 'masters.manage'),
    ('platform_admin', 'venues.verify'), ('platform_admin', 'modules.manage'),
    ('owner', 'venue.edit'), ('owner', 'venue.staff'), ('owner', 'venue.income'),
    ('manager', 'venue.edit'), ('manager', 'venue.income')
  ) d (role_key, permission_key)
  join public.roles r on r.key = d.role_key
  where d.role_key = any (v_new_roles) or d.permission_key = any (v_new_permissions)
  on conflict do nothing;
end;
$$;

