       + (select count(*) from public.venue_staff s where s.role = v_role.key)
  into v_people;
  if v_people > 0 then
    raise exception '% people have this role. Give them another role first, or turn it off.', v_people;
  end if;
  delete from public.roles r where r.id = v_role.id;
end;
$$;


